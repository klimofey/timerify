"""Writes the sentences that take over Home Assistant's own commands to turn a device on
or off, for the devices that have a Timerify timer.

Home Assistant understands "turn on the boiler" and "turn off the boiler in 15 minutes"
for every device, and runs them itself. For a device with a timer the commands must go
to Timerify instead (spec R9, §6.4): "turn on" starts the timer, "turn off in 15
minutes" sets it, "turn on in 15 minutes" is a command that waits. So the same phrasings
are written again, for Timerify's intents, from the sentences of the pinned
`home-assistant-intents`: its `name_only` commands to turn on and off (`HassTurnOn`,
`HassTurnOff`), alone, and inside each of the shapes in which `HassStartTimer` says a
delayed command ("<command> in 15 minutes", "in 15 minutes <command>", with hours,
minutes and seconds in each combination); the ways to say the delay are written once,
as two rules of the file that every command refers to. Home Assistant counts the hours,
minutes and seconds of a delay up to 100. These sentences count the hours and minutes
with Timerify's own lists, the ones a duration uses, which reach a week (`DELAY_LISTS`):
a delay past the limit of a command is then refused by the controller, and the answer
names the limit, instead of the sentence not being understood. Home Assistant has no
delay in days, and its gazetteer takes "turn off the boiler in 2 days" for a plain turn
off of the device, so the sentences of the language may define one (`OWN_DELAY_RULE`),
and each way to say a delay then has it as one more alternative. Timerify's sentences
name only the devices that have a timer, and the built-in agent prefers a custom
sentence to its own, so a device without one still reaches Home Assistant's. A
phrasing that this file does not repeat, such as one a newer release of the intents
adds, reaches Home Assistant's until the file is written again.

The file is written from the data, not retyped, and what the generator does not
understand it refuses: a block of the intents with a key it has not been taught could
widen or narrow the takeover without a word.

    uv run python -m scripts.generate_core_commands

The settings a delayed "turn on" can be said with come from the sentences of the
language (`sentences/<language>/src/timerify.yaml`): each device, thermostat and water
heater has the settings of its own there, for "turn on for an hour", and the delayed
command copies the scope and every rule of each of those blocks. So a word for an HVAC
mode or a temperature follows a thermostat's name and nothing else, and a rule that a
block says in its own way (how long, for a thermostat, whose temperature a bare number
after the hours is) is said so in the delayed command too.
"""

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from importlib.metadata import version
from pathlib import Path
from types import MappingProxyType
from typing import Any, Final, Literal

from home_assistant_intents import get_intents

from custom_components.timerify.const import SENTENCES_DIR, VOICE_LANGUAGES
from custom_components.timerify.voice.base import SPOKEN_TARGET_SLOT
from custom_components.timerify.voice.sentences import dump_sentences, read_back

COMMAND: Final = "uv run python -m scripts.generate_core_commands"
"""How the file is written again."""
FILE_NAME: Final = "core_commands.yaml"
"""The file of a language's sentences that this script writes."""
SOURCE_FILE: Final = Path("src") / "timerify.yaml"
"""Where, below a language's directory, the sentences are that tell what each kind of
device can be turned on with."""
HEADER: Final = (
    "# Generated by scripts/generate_core_commands.py"
    " from home-assistant-intents {version}. Do not edit.\n"
)

type Action = Literal["on", "off"]

CORE_COMMANDS: Final[Mapping[Action, str]] = {
    "on": "HassTurnOn",
    "off": "HassTurnOff",
}
"""The commands of Home Assistant that are taken over, by what they do."""
TIMERIFY_COMMANDS: Final[Mapping[Action, str]] = {
    "on": "TimerifyRun",
    "off": "TimerifyStop",
}
"""The intent of Timerify that a command said alone goes to."""
DELAYED_COMMAND: Final = "TimerifyDelayedCommand"
"""The intent of Timerify that a command said with a delay goes to."""
NAME_ONLY: Final = "name_only"
"""The `slot_combination` of the commands that name the device and nothing else: not an
area, a floor or a kind of device."""
GENERIC_DOMAIN: Final = "switch"
"""The domain whose commands are the generic ones, for every device that can be turned
on and off: the block of Home Assistant that lists it is the block for them all."""

COMMAND_SLOT: Final = "{timer_command:conversation_command}"
"""Where a delayed command of Home Assistant has the command it delays."""
NAME_SLOT: Final = "{name}"
"""Where a command of Home Assistant has the device it acts on."""
TARGET_SLOT: Final = "{" + SPOKEN_TARGET_SLOT + "}"
"""The same, as these sentences have it: only a device that has a timer, in the slot
that is not called `name` (see `SPOKEN_TARGET_SLOT`)."""
COMMAND_RULE_NAME: Final = "timerify_command"
"""The rule of a block of delayed commands that says the command in the way the block
does (`command_group`)."""
COMMAND_RULE: Final = f"<{COMMAND_RULE_NAME}>"
"""Where a delayed command of these sentences has the command it delays. A rule of the
block, since the block says it in the same way in each of its sentences, and the
built-in agent parses every sentence it loads."""
DELAY_AFTER_RULE_NAME: Final = "timerify_delay_after_command"
DELAY_BEFORE_RULE_NAME: Final = "timerify_delay_before_command"
"""The rules, in the file, that say a delay in the ways Home Assistant says it after the
command and before it ("in 15 minutes", "in an hour and 5 minutes"). Written once, since
each command in each block says the same delays (`delay_rules`)."""
OWN_DELAY_RULE: Final = "timerify_delay_in_days"
"""The rule, in the sentences of a language (`SOURCE_FILE`), that says a delay in days,
which Home Assistant has no sentence for: one more way to say a delay, wherever the
rules above say one, if the language defines it."""
EXTRAS: Final = "<timerify_run_extras>"
"""What a command to turn on may say besides when: how long to run, and the settings."""
EXTRAS_RULE: Final = (
    "(<timerify_for_part> [<timerify_settings>]"
    "|<timerify_settings> [<timerify_for_part>])"
)
"""What `EXTRAS` is in a block: how long, the settings, or both, in either order, and
never neither. The settings are those of the block's scope."""

DELAY_LISTS: Final[Mapping[str, str]] = {
    "hours": "{timerify_hours:delay_hours}",
    "minutes": (
        "({timerify_minutes:delay_minutes}|{timerify_long_minutes:delay_minutes})"
    ),
    "seconds": "{timer_seconds:delay_seconds}",
}
"""What says the count of each unit of a delay, in place of Home Assistant's list of
`{timer_<unit>:<unit>}` (1 to 100): Timerify's own lists of hours and minutes, the ones
a duration uses (`sentences/<language>/src/timerify.yaml`), which reach a week; the
seconds stay Home Assistant's. The slot is `delay_<unit>` for each, since `hours` and
`minutes` are how long a command to turn on runs."""

_SLOT: Final = re.compile(r"\{[^{}]*\}")
_DELAY_SLOT: Final = re.compile(r"\{timer_(hours|minutes|seconds):\1\}")

_UNDERSTOOD_COMMAND_KEYS: Final = frozenset(
    {"sentences", "metadata", "requires_context", "response"}
)
_UNDERSTOOD_SHAPE_KEYS: Final = frozenset({"sentences", "metadata", "response"})


@dataclass(frozen=True)
class CommandBlock:
    """A block of Home Assistant's sentences that turns a device on or off by name."""

    action: Action
    sentences: tuple[str, ...]
    """The sentences, each with the name as `{name}`."""
    domains: tuple[str, ...]
    """The domains of the devices the block is for; none, for every domain."""

    @property
    def generic(self) -> bool:
        """Whether the block is for every device that has a timer, whatever its
        domain."""
        return not self.domains or GENERIC_DOMAIN in self.domains

    @property
    def scope(self) -> tuple[str, ...]:
        """The domains of the devices that have a timer that the block is for; none, for
        every domain. The generic block is the one for them all."""
        return () if self.generic else self.domains


@dataclass(frozen=True)
class Scope:
    """The devices a set of settings can be said of: the domains it is for, or, if there
    are none, every domain but the ones left out."""

    requires: tuple[str, ...]
    excludes: tuple[str, ...]
    rules: Mapping[str, str]
    """Every expansion rule of the block of `TimerifyRun` that has the scope, by name.
    It holds `timerify_settings`, and may hold a rule that changes how another is said
    for these devices alone (the words for how long, for a thermostat)."""


def _domains_of(values: object) -> tuple[str, ...]:
    """A domain or a list of them, as the sentences write a context, as a tuple."""
    if values is None:
        return ()
    if isinstance(values, str):
        return (values,)
    if isinstance(values, Sequence):
        return tuple(str(value) for value in values)
    raise ValueError(f"A domain context that is neither a name nor a list: {values!r}")


def _refuse_unknown(
    what: str, block: Mapping[str, Any], understood: frozenset[str]
) -> None:
    """Raise ValueError if the block of sentences has a key the generator has not been
    taught."""
    if unknown := sorted(set(block) - understood):
        raise ValueError(
            f"{what} has {', '.join(unknown)}, which this generator does not"
            " understand: teach it, or the takeover would widen or narrow without a"
            " word"
        )


def command_blocks(data: Mapping[str, Any]) -> list[CommandBlock]:
    """The blocks of the intents `data` that turn a device on or off by its name alone:
    those of `HassTurnOn` and `HassTurnOff` whose `slot_combination` is `name_only`.

    Raises ValueError for a block with a key the generator does not understand
    (`excludes_context`, a list or an expansion rule of its own, ...), or a context that
    is not about the domain.
    """
    blocks: list[CommandBlock] = []
    for action, intent_name in CORE_COMMANDS.items():
        for block in data["intents"][intent_name]["data"]:
            if block.get("metadata", {}).get("slot_combination") != NAME_ONLY:
                continue
            what = (
                f"A {NAME_ONLY} block of {intent_name} ({block['sentences'][0]!r}...)"
            )
            _refuse_unknown(what, block, _UNDERSTOOD_COMMAND_KEYS)
            required = block.get("requires_context", {})
            if set(required) - {"domain"}:
                raise ValueError(
                    f"{what} requires context other than the domain: {sorted(required)}"
                )
            blocks.append(
                CommandBlock(
                    action,
                    tuple(block["sentences"]),
                    _domains_of(required.get("domain")),
                )
            )
    return blocks


def delayed_shape_blocks(data: Mapping[str, Any]) -> list[tuple[str, ...]]:
    """The blocks of `HassStartTimer` that say a delayed command, `response: command`:
    for each, the sentences that say it, one for each order of the command and the
    delay.

    Raises ValueError for a block with a key the generator does not understand.
    """
    blocks: list[tuple[str, ...]] = []
    for block in data["intents"]["HassStartTimer"]["data"]:
        if block.get("response") != "command":
            continue
        _refuse_unknown(
            f"A delayed command of HassStartTimer ({block['sentences'][0]!r}...)",
            block,
            _UNDERSTOOD_SHAPE_KEYS,
        )
        blocks.append(tuple(block["sentences"]))
    return blocks


def delayed_shapes(data: Mapping[str, Any]) -> list[str]:
    """The sentences that say a delayed command in the intents `data`: where the command
    and the delay are, and how the delay is said."""
    return [shape for block in delayed_shape_blocks(data) for shape in block]


def _flat(sentence: str) -> str:
    """The sentence, if it has no alternative outside a group: put in a group with
    others, it would be read as several."""
    depth = 0
    for character in sentence:
        if character in "([":
            depth += 1
        elif character in ")]":
            depth -= 1
        elif character == "|" and depth == 0:
            raise ValueError(
                f"A sentence with an alternative outside a group: {sentence!r}"
            )
    return sentence


def _about_the_target(sentence: str) -> str:
    """A sentence of Home Assistant that acts on a device, as one that acts on a device
    that has a timer."""
    if _SLOT.findall(sentence) != [NAME_SLOT]:
        raise ValueError(f"A command that is not about {NAME_SLOT} alone: {sentence!r}")
    return _flat(sentence).replace(NAME_SLOT, TARGET_SLOT)


def command_group(block: CommandBlock) -> str:
    """The sentences of the block as one part of a sentence: any of them, naming a
    device that has a timer."""
    return "(" + "|".join(_about_the_target(s) for s in block.sentences) + ")"


def delay_rules(data: Mapping[str, Any], sources: Mapping[str, Any]) -> dict[str, str]:
    """The rules that say a delay, from the delayed commands in the intents `data`: the
    delays that Home Assistant says after the command, and those it says before it, by
    the name of the rule; a rule only if there is a delay to say in that place.

    A delay is said with the slots `delay_hours`, `delay_minutes` and `delay_seconds`,
    since `hours` and `minutes` are how long a command to turn on runs, and its hours
    and minutes with Timerify's lists (`DELAY_LISTS`). If the sentences `sources` of the
    language define the rule of a delay in days (`OWN_DELAY_RULE`), each rule has it as
    one more way to say a delay.

    Raises ValueError for a shape whose command is not at one end and set apart by a
    space, or that has anything but the command and the delay in it.
    """
    after: list[str] = []
    before: list[str] = []
    for shape in delayed_shapes(data):
        if shape.count(COMMAND_SLOT) != 1:
            raise ValueError(
                f"A delayed command that does not have {COMMAND_SLOT}: {shape!r}"
            )
        for slot in _SLOT.findall(shape.replace(COMMAND_SLOT, "")):
            if not _DELAY_SLOT.fullmatch(slot):
                raise ValueError(f"A delayed command with {slot} in it: {shape!r}")
        delay = _DELAY_SLOT.sub(lambda found: DELAY_LISTS[found[1]], shape)
        if shape.startswith(f"{COMMAND_SLOT} "):
            after.append(_flat(delay.removeprefix(f"{COMMAND_SLOT} ")))
        elif shape.endswith(f" {COMMAND_SLOT}"):
            before.append(_flat(delay.removesuffix(f" {COMMAND_SLOT}")))
        else:
            raise ValueError(
                f"A delayed command with the command not at an end: {shape!r}"
            )
    defined = OWN_DELAY_RULE in sources.get("expansion_rules", {})
    own = [f"<{OWN_DELAY_RULE}>"] if defined else []
    places = {DELAY_AFTER_RULE_NAME: after, DELAY_BEFORE_RULE_NAME: before}
    return {
        name: "(" + "|".join([*delays, *own]) + ")"
        for name, delays in places.items()
        if delays
    }


def delayed_sentences(block: CommandBlock, rules: Mapping[str, str]) -> list[str]:
    """The sentences that say the command of `block` with a delay, naming a device that
    has a timer, from the rules that say the delay (`delay_rules`), in each place that
    one is for.

    A command to turn off is said as Home Assistant says it. One to turn on may also say
    how long it runs, and with what settings (`EXTRAS`), once and not more: before the
    delay, or after it if the command comes first, and after the command if the delay
    does.
    """
    sentences: list[str] = []
    if DELAY_AFTER_RULE_NAME in rules:
        later = f"{COMMAND_RULE} <{DELAY_AFTER_RULE_NAME}>"
        sentences.append(later)
        if block.action == "on":
            sentences += [
                f"{COMMAND_RULE} {EXTRAS} <{DELAY_AFTER_RULE_NAME}>",
                f"{later} {EXTRAS}",
            ]
    if DELAY_BEFORE_RULE_NAME in rules:
        earlier = f"<{DELAY_BEFORE_RULE_NAME}> {COMMAND_RULE}"
        sentences.append(earlier if block.action == "off" else f"{earlier} [{EXTRAS}]")
    return sentences


def run_scopes(sources: Mapping[str, Any]) -> list[Scope]:
    """The scopes of the settings that a command to turn on is said with, from the
    sentences `sources` of a language: the blocks of `TimerifyRun` that have a rule
    `timerify_settings` of their own, with every rule they have.

    Raises ValueError if there are none.
    """
    scopes = [
        Scope(
            _domains_of(block.get("requires_context", {}).get("domain")),
            _domains_of(block.get("excludes_context", {}).get("domain")),
            MappingProxyType(dict(block["expansion_rules"])),
        )
        for block in sources["intents"][TIMERIFY_COMMANDS["on"]]["data"]
        if "timerify_settings" in block.get("expansion_rules", {})
    ]
    if not scopes:
        raise ValueError(
            f"No block of {TIMERIFY_COMMANDS['on']} has a rule timerify_settings:"
            " there is nothing to say a delayed command to turn on with"
        )
    return scopes


def _context(domains: Sequence[str], excluded: Sequence[str] = ()) -> dict[str, Any]:
    """The context of a block of sentences for the devices of `domains`, or, if there
    are none, for every device but those of the domains `excluded`."""
    if domains:
        return {"requires_context": {"domain": list(domains)}}
    if excluded:
        return {"excludes_context": {"domain": list(excluded)}}
    return {}


def scoped(scope: Sequence[str], settings: Scope) -> dict[str, Any] | None:
    """The context of a block that says a command for the devices of `scope` (every
    domain, if there are none) with the settings of `settings`; None when no device is
    in both."""
    domains = list(scope)
    if settings.requires:
        domains = [d for d in settings.requires if not scope or d in scope]
        if not domains:
            return None
    if domains:
        domains = [d for d in domains if d not in settings.excludes]
        return _context(domains) if domains else None
    return _context((), settings.excludes)


def _bare_blocks(
    blocks: Sequence[CommandBlock], action: Action
) -> list[dict[str, Any]]:
    """The data blocks that say a command to turn on or off alone."""
    return [
        {
            "sentences": [_about_the_target(sentence) for sentence in block.sentences],
            **_context(block.scope),
        }
        for block in blocks
        if block.action == action
    ]


def _delayed_blocks(
    blocks: Sequence[CommandBlock], scopes: Sequence[Scope], delays: Mapping[str, str]
) -> list[dict[str, Any]]:
    """The data blocks that say a command to turn on or off after a delay, said by the
    rules `delays`: for each command, one block for a command to turn off, and for a
    command to turn on one for each scope of settings that devices of its domains are
    in."""
    delayed: list[dict[str, Any]] = []
    for block in blocks:
        rules = {COMMAND_RULE_NAME: command_group(block)}
        common: dict[str, Any] = {
            "sentences": delayed_sentences(block, delays),
            "slots": {"action": block.action},
            "response": "delayed",
        }
        if block.action == "off":
            delayed.append(
                {**common, **_context(block.scope), "expansion_rules": rules}
            )
            continue
        for settings in scopes:
            if (context := scoped(block.scope, settings)) is not None:
                delayed.append(
                    {
                        **common,
                        **context,
                        "expansion_rules": {
                            **rules,
                            **settings.rules,
                            "timerify_run_extras": EXTRAS_RULE,
                        },
                    }
                )
    return delayed


def render(language: str) -> str:
    """The text of the file of `language`: the commands of Home Assistant to turn on and
    off, alone and delayed, for the devices that have a timer."""
    data = get_intents(language)
    if data is None:
        raise ValueError(f"home-assistant-intents has no sentences in {language}")
    sources = read_back((SENTENCES_DIR / language / SOURCE_FILE).read_text("utf-8"))
    blocks = command_blocks(data)
    delays = delay_rules(data, sources)
    sentences = {
        "language": language,
        "expansion_rules": delays,
        "intents": {
            TIMERIFY_COMMANDS["on"]: {"data": _bare_blocks(blocks, "on")},
            TIMERIFY_COMMANDS["off"]: {"data": _bare_blocks(blocks, "off")},
            DELAYED_COMMAND: {
                "data": _delayed_blocks(blocks, run_scopes(sources), delays)
            },
        },
    }
    header = HEADER.format(version=version("home-assistant-intents"))
    return header + dump_sentences(sentences)


def main() -> None:
    """Write the file of every language."""
    for language in VOICE_LANGUAGES:
        (SENTENCES_DIR / language / FILE_NAME).write_text(render(language), "utf-8")


if __name__ == "__main__":
    main()
