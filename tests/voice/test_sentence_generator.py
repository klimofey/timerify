"""The shipped sentence files and where they come from: the sources written by hand, the
macros of each language written once, and the generator that puts them together; and
every answer the files hold, said by the built-in agent's own template engine.
"""

import re
from pathlib import Path

import pytest
from homeassistant.core import HomeAssistant

from custom_components.timerify.const import SENTENCES_DIR, VOICE_LANGUAGES
from custom_components.timerify.voice.sentences import load_sources, read_back
from scripts.generate_core_commands import FILE_NAME as CORE_COMMANDS
from scripts.generate_sentences import (
    COMMAND,
    SOURCES,
    expand,
    macros_of,
    render,
    stale,
    write,
)

from .helpers import RESPONSE_SLOTS, render_response

MACROS = """
{#- A comment, which is not a macro. -#}
{%- macro one(n) -%}
  {{ n }}
{%- endmacro -%}

{%- macro twice(n) -%}
  {{ one(n) }}{{ one(n) }}
{%- endmacro -%}

{%- macro unused(n) -%}
  {{ n }}
{%- endmacro -%}
"""


@pytest.mark.parametrize("language", VOICE_LANGUAGES)
def test_shipped_sentence_files_are_current(language: str) -> None:
    """The files that are shipped, and that the managed files and the manual
    installation are made from, are what the generator writes from the sources."""
    generated = render(language)

    assert generated
    for name, text in generated.items():
        shipped = (SENTENCES_DIR / language / name).read_text("utf-8")
        assert shipped == text, (
            f"sentences/{language}/{name} is not what the generator writes from"
            f" sentences/{language}/src: run `{COMMAND}` and commit the result"
        )


@pytest.mark.parametrize("language", VOICE_LANGUAGES)
def test_there_are_no_other_shipped_sentence_files(language: str) -> None:
    """A file whose source was removed or renamed would still ship, and the managed
    files and the manual installation would still be made from it. The sentences that
    take over the commands of Home Assistant are the one file with another generator."""
    shipped = {path.name for path in (SENTENCES_DIR / language).glob("*.yaml")}

    assert shipped == {*render(language), CORE_COMMANDS}, (
        f"sentences/{language} has files the generator does not write from its"
        f" sources: run `{COMMAND}`, which removes them, and commit the result"
    )


@pytest.mark.parametrize("language", VOICE_LANGUAGES)
def test_shipped_answers_are_blocks_not_lines_of_escapes(language: str) -> None:
    """The shipped files are the ones people read to copy a sentence or to see how an
    answer is said."""
    for name, text in render(language).items():
        answers = read_back(
            (SENTENCES_DIR / language / SOURCES / name).read_text("utf-8")
        )
        for keys in answers.get("responses", {}).get("intents", {}).values():
            for key in keys:
                assert re.search(rf"^\s+{key}: \|-?$", text, re.MULTILINE), (name, key)


@pytest.mark.parametrize("language", VOICE_LANGUAGES)
def test_shipped_sentence_files_say_that_they_are_generated(language: str) -> None:
    for name in render(language):
        first_line = (
            (SENTENCES_DIR / language / name).read_text("utf-8").splitlines()[0]
        )
        assert first_line.startswith("# Generated by scripts/generate_sentences.py")


@pytest.mark.parametrize("language", VOICE_LANGUAGES)
async def test_every_answer_renders_in_every_case_it_tells_apart(
    hass: HomeAssistant, language: str
) -> None:
    """Each answer of each language, with the slots of every case it tells apart, is a
    template that renders to a sentence about the target: a macro that is missing or a
    branch that fails shows here, though the scenarios reach only some branches."""
    sources = await hass.async_add_executor_job(load_sources, language)
    answers = {
        (intent_type, key): template
        for intent_type, keys in sources["responses"]["intents"].items()
        for key, template in keys.items()
    }

    assert answers.keys() == RESPONSE_SLOTS.keys()
    for pair, template in answers.items():
        for slots in RESPONSE_SLOTS[pair]:
            said = render_response(hass, template, slots)
            assert slots["target"] in said, (language, pair, slots, said)
            assert not {"{", "}", "%", "~"} & set(said), (language, pair, slots, said)


def test_an_answer_gets_the_macros_it_calls_and_those_they_call() -> None:
    """In the order of the macros file, in front of the answer, and no other."""
    expanded = expand("{{ twice(2) }}", macros_of(MACROS))

    assert expanded.index("macro one") < expanded.index("macro twice")
    assert "macro unused" not in expanded
    assert expanded.endswith("{{ twice(2) }}")


async def test_an_expanded_answer_renders_as_the_macros_say(
    hass: HomeAssistant,
) -> None:
    expanded = expand("{{ twice(slots.count) }}", macros_of(MACROS))

    assert render_response(hass, expanded, {"count": 7}) == "77"


def test_an_answer_that_calls_no_macro_is_left_as_it_is() -> None:
    assert expand("{{ slots.target }} is off.", macros_of(MACROS)) == (
        "{{ slots.target }} is off."
    )


def test_a_macros_file_that_holds_anything_but_macros_is_refused() -> None:
    """Whatever is not in a macro would be left out of every answer without a word."""
    with pytest.raises(ValueError, match="more than macros and comments"):
        macros_of(MACROS + "{% set stray = 1 %}")


def test_writing_leaves_the_file_of_the_other_generator_alone(tmp_path: Path) -> None:
    """The commands of Home Assistant have no source in `src`; they are written from
    the intents by `scripts/generate_core_commands.py`, and this script must neither
    remove them as stale nor write over them."""
    sources = tmp_path / "en" / SOURCES
    sources.mkdir(parents=True)
    (sources / "macros.jinja").write_text(MACROS, "utf-8")
    (sources / "words.yaml").write_text("language: en\n", "utf-8")
    (tmp_path / "en" / CORE_COMMANDS).write_text("language: en\n# theirs\n", "utf-8")

    assert stale("en", tmp_path) == []
    write("en", tmp_path)

    assert (tmp_path / "en" / CORE_COMMANDS).read_text("utf-8") == (
        "language: en\n# theirs\n"
    )


def test_writing_replaces_the_shipped_files_and_removes_those_without_a_source(
    tmp_path: Path,
) -> None:
    """Run by a developer after a source was renamed: the file of the old name goes,
    the file of the new one is written, and the sources are left as they are."""
    sources = tmp_path / "en" / SOURCES
    sources.mkdir(parents=True)
    (sources / "macros.jinja").write_text(MACROS, "utf-8")
    (sources / "new_name.yaml").write_text(
        "responses:\n  intents:\n    Ask:\n      default: '{{ twice(slots.n) }}'\n",
        "utf-8",
    )
    (tmp_path / "en" / "old_name.yaml").write_text("language: en\n", "utf-8")
    (tmp_path / "en" / "notes.txt").write_text("not a sentence file\n", "utf-8")

    assert [path.name for path in stale("en", tmp_path)] == ["old_name.yaml"]
    write("en", tmp_path)

    assert sorted(path.name for path in (tmp_path / "en").iterdir()) == [
        "new_name.yaml",
        "notes.txt",
        SOURCES,
    ]
    assert stale("en", tmp_path) == []
    assert "macro twice" in (tmp_path / "en" / "new_name.yaml").read_text("utf-8")
    assert sorted(path.name for path in sources.iterdir()) == [
        "macros.jinja",
        "new_name.yaml",
    ]
