"""Writes the sentence files Timerify ships for the built-in agent from their sources.

A source, `sentences/<language>/src/<name>.yaml`, is written by hand. Its answers are
Jinja templates that call macros by name, and the macros are written once for the
language, in `sentences/<language>/src/macros.jinja`: the plural forms of a count, the
words for a day. The shipped file `sentences/<language>/<name>.yaml` is the same data
with, in front of each answer, the definition of every macro the answer calls and of
the macros those call, since the built-in agent renders an answer on its own and cannot
import a macro. The managed files and the manual installation use the shipped files.

    uv run python -m scripts.generate_sentences
"""

import re
from collections.abc import Mapping
from pathlib import Path
from typing import Any, Final

from homeassistant.util.yaml import dump, load_yaml_dict

from custom_components.timerify.const import SENTENCES_DIR, VOICE_LANGUAGES

COMMAND: Final = "uv run python -m scripts.generate_sentences"
"""How the shipped files are written again."""
SOURCES: Final = "src"
"""The directory of a language that holds its sources."""
MACROS: Final = "macros.jinja"
"""The file of a language's sources that holds its macros."""
HEADER: Final = (
    "# Generated by scripts/generate_sentences.py from src/{name} and src/{macros}:\n"
    "# do not edit this file. Edit the sources and run `{command}`.\n"
)

_COMMENT: Final = re.compile(r"\{#.*?#\}", re.DOTALL)
_MACRO: Final = re.compile(
    r"\{%-?\s*macro\s+(?P<name>\w+)\s*\(.*?\{%-?\s*endmacro\s*-?%\}", re.DOTALL
)


def macros_of(text: str) -> dict[str, str]:
    """The macros of a macros file by name, each as its block from `macro` to
    `endmacro`, in the order of the file. Nothing but macros and comments may be there:
    anything else would be left out of the answers without a word."""
    uncommented = _COMMENT.sub("", text)
    if leftover := _MACRO.sub("", uncommented).strip():
        raise ValueError(f"{MACROS} holds more than macros and comments: {leftover!r}")
    return {found["name"]: found[0] for found in _MACRO.finditer(uncommented)}


def expand(template: str, macros: Mapping[str, str]) -> str:
    """`template` with the macros it calls in front of it, and the macros those call.
    The macros come in the order of the macros file, in which a macro calls only those
    above it."""
    needed: set[str] = set()
    unread = [template]
    while unread:
        text = unread.pop()
        for name, definition in macros.items():
            if name not in needed and re.search(rf"\b{name}\(", text):
                needed.add(name)
                unread.append(definition)
    return "\n".join([*(m for name, m in macros.items() if name in needed), template])


def _expand_answers(answers: Any, macros: Mapping[str, str]) -> Any:
    """The answers of a source, a tree of templates, with each template expanded."""
    if isinstance(answers, str):
        return expand(answers, macros)
    return {key: _expand_answers(value, macros) for key, value in answers.items()}


def render(language: str) -> dict[str, str]:
    """The text of each shipped file of `language`, by file name."""
    sources = SENTENCES_DIR / language / SOURCES
    macros = macros_of((sources / MACROS).read_text("utf-8"))
    files: dict[str, str] = {}
    for path in sorted(sources.glob("*.yaml")):
        data = load_yaml_dict(path)
        if "responses" in data:
            data["responses"] = _expand_answers(data["responses"], macros)
        header = HEADER.format(name=path.name, macros=MACROS, command=COMMAND)
        files[path.name] = header + dump(data)
    return files


def main() -> None:
    """Write the shipped files of every language."""
    for language in VOICE_LANGUAGES:
        for name, text in render(language).items():
            Path(SENTENCES_DIR / language / name).write_text(text, "utf-8")


if __name__ == "__main__":
    main()
